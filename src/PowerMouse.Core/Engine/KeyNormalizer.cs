using PowerMouse.Core.Models;

namespace PowerMouse.Core.Engine;

public static class KeyNormalizer
{
    public static int Normalize(KeyboardStroke stroke)
    {
        if (stroke.VirtualKey == VirtualKeys.Shift)
        {
            return stroke.ScanCode == 0x36 ? VirtualKeys.RightShift : VirtualKeys.LeftShift;
        }

        if (stroke.VirtualKey == VirtualKeys.Control)
        {
            return stroke.IsExtended ? VirtualKeys.RightControl : VirtualKeys.LeftControl;
        }

        if (stroke.VirtualKey == VirtualKeys.Menu)
        {
            return stroke.IsExtended ? VirtualKeys.RightMenu : VirtualKeys.LeftMenu;
        }

        if (stroke.VirtualKey == VirtualKeys.Return && stroke.IsExtended && stroke.ScanCode == 0x1C)
        {
            return VirtualKeys.NumpadEnter;
        }

        // The non-extended navigation scan codes are generated by the numeric
        // keypad when Num Lock and Shift change the reported virtual key.
        if (!stroke.IsExtended)
        {
            return stroke.ScanCode switch
            {
                0x52 => VirtualKeys.Numpad0,
                0x4F => VirtualKeys.Numpad1,
                0x50 => VirtualKeys.Numpad2,
                0x51 => VirtualKeys.Numpad3,
                0x4B => VirtualKeys.Numpad4,
                0x4C => VirtualKeys.Numpad5,
                0x4D => VirtualKeys.Numpad6,
                0x47 => VirtualKeys.Numpad7,
                0x48 => VirtualKeys.Numpad8,
                0x49 => VirtualKeys.Numpad9,
                0x53 => VirtualKeys.NumpadDecimal,
                _ => stroke.VirtualKey,
            };
        }

        return stroke.VirtualKey;
    }
}
